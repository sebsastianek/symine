<?php

declare(strict_types=1);

namespace App\Tests\Parity;

use App\Entity\Issue;
use App\Entity\Project;
use App\Entity\User;
use App\Mailer\NotificationRecipients;
use App\Query\QueryFactory;
use App\Security\Authorization;
use App\Security\CurrentUser;
use App\Service\Activity\ActivityFetcher;
use App\Service\Activity\SearchService;
use App\Service\TimeEntryService;
use App\Tests\Integration\SymineTestCase;

/**
 * Behavioural parity snapshots: Symine's answers compared with the oracle recorded from the reference Redmine
 * on the same (migrated) data - tests/fixtures/redmine-expectations.json, generated by
 * tests/fixtures/redmine_expectations.rb on a pristine copy of tests/fixtures/redmine-seeded.db.
 */
final class RedmineBehaviourParityTest extends SymineTestCase
{
    private const array LOGINS = ['admin', 'jsmith', 'dlopper', 'rhill', 'anna', 'anonymous'];

    private array $exp;

    protected function setUp(): void
    {
        parent::setUp();
        $this->exp = json_decode((string) file_get_contents(\dirname(__DIR__).'/fixtures/redmine-expectations.json'), true);
    }

    private function as(string $login): User
    {
        $user = 'anonymous' === $login ? $this->service(CurrentUser::class)->anonymous() : $this->user($login);
        $this->actAs($user);

        return $user;
    }

    private function project(string $identifier): Project
    {
        $p = $this->em->getRepository(Project::class)->findOneBy(['identifier' => $identifier]);
        self::assertNotNull($p);

        return $p;
    }

    /** Project.visible(user) */
    public function testVisibleProjects(): void
    {
        $auth = $this->service(Authorization::class);
        foreach (self::LOGINS as $login) {
            $user = $this->as($login);
            $ids = $auth->visibleProjectIds($user);
            sort($ids);
            self::assertSame($this->exp['visible_projects'][$login], $ids, "Project.visible($login)");
        }
    }

    /** Project.allowed_to(user, permission) */
    public function testProjectsAllowedTo(): void
    {
        $auth = $this->service(Authorization::class);
        foreach (self::LOGINS as $login) {
            $user = $this->as($login);
            foreach (['view_issues', 'view_time_entries', 'view_wiki_pages', 'log_time', 'add_issues', 'view_news'] as $perm) {
                $cond = $auth->allowedToCondition($perm, 'p.id', $user);
                $ids = array_map('intval', $this->em->createQuery("SELECT p.id FROM App\\Entity\\Project p WHERE $cond ORDER BY p.id")->getSingleColumnResult());
                self::assertSame($this->exp['projects_allowed_to']["$perm|$login"], $ids, "Project.allowed_to($login, :$perm)");
            }
        }
    }

    /** Redmine::Activity::Fetcher#events with the :all and :default scopes, globally and per project (with subprojects) */
    public function testActivityEvents(): void
    {
        $fetcher = $this->service(ActivityFetcher::class);
        foreach (['*', 'ecommerce', 'internal'] as $identifier) {
            foreach (self::LOGINS as $login) {
                $user = $this->as($login);
                $project = '*' === $identifier ? null : $this->project($identifier);
                $types = $fetcher->eventTypes($user, $project);
                // the core event types only (plugins may register more)
                $types = array_values(array_intersect($types, array_keys(ActivityFetcher::EVENT_TYPES)));
                foreach (['all' => $types, 'default' => array_values(array_intersect(ActivityFetcher::defaultEventTypes(), $types))] as $scope => $scopeTypes) {
                    $events = array_map(static fn ($e) => $e->type.'#'.$e->id, $fetcher->events($user, $scopeTypes, $project, true));
                    sort($events);
                    self::assertSame($this->exp['activity']["$identifier|$scope|$login"], $events, "activity of $identifier ($scope) as $login");
                }
            }
        }
    }

    /** Redmine::Search::Fetcher#result_ids (all types, all projects), with all words / any word / titles only */
    public function testSearchResults(): void
    {
        $search = $this->service(SearchService::class);
        foreach ($this->exp['search'] as $key => $expected) {
            [$question, $mode, $login] = explode('|', $key);
            $user = $this->as($login);
            $options = match ($mode) {
                'any' => ['all_words' => false],
                'titles' => ['titles_only' => true, 'all_words' => true],
                default => ['all_words' => true],
            };
            $ids = array_map(static fn (array $r) => $r[0].'#'.$r[1], $search->resultIds(SearchService::tokens($question), $user, SearchService::TYPES, null, $options));
            self::assertSame($expected, $ids, "search \"$question\" ($mode) as $login");
        }
    }

    /** Issue#notified_users and Issue#notified_watchers with several notification preferences */
    public function testNotifiedUsersAndWatchers(): void
    {
        $conn = $this->em->getConnection();
        $scenarios = [
            'default' => [],
            'all' => ["UPDATE users SET mail_notification = 'all' WHERE type = 'User'"],
            'mixed' => [
                "UPDATE users SET mail_notification = 'none' WHERE login = 'admin'",
                "UPDATE users SET mail_notification = 'selected' WHERE login = 'jsmith'",
                'UPDATE members SET mail_notification = 1 WHERE user_id = 5 AND project_id = 1',
                "UPDATE users SET mail_notification = 'only_my_events' WHERE login = 'dlopper'",
                "UPDATE users SET mail_notification = 'only_owner' WHERE login = 'rhill'",
                "UPDATE users SET mail_notification = 'all' WHERE login = 'anna'",
            ],
        ];
        foreach ($scenarios as $label => $statements) {
            foreach ($statements as $sql) {
                $conn->executeStatement($sql);
            }
            $this->em->clear();
            $this->service(Authorization::class)->reset();
            $recipients = $this->service(NotificationRecipients::class);
            $recipients->reset();
            foreach ($this->em->getRepository(Issue::class)->findBy([], ['id' => 'ASC']) as $issue) {
                $users = array_map(static fn (User $u) => $u->login, $recipients->issueNotifiedUsers($issue));
                $watchers = array_map(static fn (User $u) => $u->login, $recipients->issueNotifiedWatchers($issue));
                sort($users);
                sort($watchers);
                self::assertSame($this->exp['notified']["{$issue->id}|$label|users"], $users, "notified_users of #{$issue->id} ($label)");
                self::assertSame($this->exp['notified']["{$issue->id}|$label|watchers"], $watchers, "notified_watchers of #{$issue->id} ($label)");
            }
        }
    }

    /** TimeEntry.visible and the TimeEntryQuery hours total, with the default and "own" time entry visibility */
    public function testTimeEntryVisibilityAndTotals(): void
    {
        foreach (['default' => [], 'own' => ["UPDATE roles SET time_entries_visibility = 'own' WHERE builtin IN (1, 2) OR name = 'Reporter'"]] as $label => $statements) {
            foreach ($statements as $sql) {
                $this->em->getConnection()->executeStatement($sql);
            }
            $this->em->clear();
            foreach (self::LOGINS as $login) {
                $user = $this->as($login);
                $cond = $this->service(TimeEntryService::class)->visibleCondition($user, 'te');
                $ids = array_map('intval', $this->em->createQuery("SELECT te.id FROM App\\Entity\\TimeEntry te JOIN te.project p WHERE $cond ORDER BY te.id")->getSingleColumnResult());
                self::assertSame($this->exp['time_entries']["$label|$login"], $ids, "TimeEntry.visible($login) ($label)");

                $factory = $this->service(QueryFactory::class);
                \App\EventSubscriber\TimeEntryQueryRegistrationSubscriber::register($factory);
                $q = $factory->create('TimeEntryQuery');
                $q->addFilter('spent_on', '*', ['']);
                $q->setTotalableNames(['hours']);
                $hours = null;
                foreach ($q->totalableColumns() as $c) {
                    if ('hours' === $c->name) {
                        $hours = round((float) $q->totalFor($c), 2);
                    }
                }
                self::assertEquals($this->exp['time_entries']["$label|$login|total"], [$q->count(), $hours], "time entry query totals as $login ($label)");
            }
        }
    }

    /** IssueQuery#issue_count, #total_for and grouped counts/totals */
    public function testIssueQueryTotals(): void
    {
        foreach (['*', 'ecommerce'] as $identifier) {
            foreach (self::LOGINS as $login) {
                $this->as($login);
                $project = '*' === $identifier ? null : $this->project($identifier);
                $q = $this->service(QueryFactory::class)->issueQuery($project);
                $q->addFilter('status_id', '*', ['']);
                $q->setTotalableNames(['estimated_hours', 'spent_hours']);
                $exp = $this->exp['totals']["$identifier|$login"];
                self::assertSame($exp['count'], $q->issueCount(), "issue count of $identifier as $login");
                self::assertEquals($exp['estimated_hours'], round((float) $q->totalFor('estimated_hours'), 2), "estimated hours of $identifier as $login");
                self::assertEquals($exp['spent_hours'], round((float) $q->totalFor('spent_hours'), 2), "spent hours of $identifier as $login");

                $q->setGroupBy('tracker');
                $names = $this->trackerNames();
                $byTracker = [];
                foreach ($q->resultCountByGroup() ?? [] as $k => $count) {
                    $byTracker[$names[(string) $k] ?? (string) $k] = $count;
                }
                ksort($byTracker);
                self::assertSame($exp['by_tracker'], $byTracker, "issue count by tracker of $identifier as $login");
                $estimated = [];
                foreach ($q->totalByGroupFor('estimated_hours') ?? [] as $k => $v) {
                    $estimated[$names[(string) $k] ?? (string) $k] = round((float) $v, 2);
                }
                ksort($estimated);
                self::assertEquals($exp['estimated_by_tracker'], $estimated, "estimated hours by tracker of $identifier as $login");
            }
        }
    }

    /** @return array<string, string> tracker id => name */
    private function trackerNames(): array
    {
        $out = [];
        foreach ($this->em->getConnection()->fetchAllAssociative('SELECT id, name FROM trackers') as $r) {
            $out[(string) $r['id']] = $r['name'];
        }

        return $out;
    }
}
